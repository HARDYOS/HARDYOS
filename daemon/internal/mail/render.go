// derive makes a value from the auth secret that's only good for one use
// (the auth policy nonce), so the secret itself appears once.
func derive(secret, purpose string) string {
	m := hmac.New(sha256.New, []byte(secret))
	m.Write([]byte("hardyos-mail\x00" + purpose))
	return hex.EncodeToString(m.Sum(nil))
}

// Render produces every configuration file for c, which must have passed
// Normalize.
func Render(c RootConfig, s RootSecrets, e Env) []File {
	var files []File
	files = append(files, renderPostfix(c, s, e)...)
	files = append(files, renderDovecot(c, s, e)...)
	files = append(files, renderRspamd(c, s, e)...)
	files = append(files, renderRadicale(c, s, e)...)
	files = append(files, File{Path: RedisConf, Mode: 0o640, Group: "redis", Content: renderRedis()})
	files = append(files, File{Path: NFTFile, Mode: 0o644, Content: RenderNFT(c.VPSPeer, c.NetBirdIface)})
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files
}

// texthash lines: "key value".
func mapFile(lines [][2]string) string {
	var b strings.Builder
	b.WriteString("# " + generatedHeader + "\n")
	for _, l := range lines {
		b.WriteString(l[0] + " " + l[1] + "\n")
	}
	return b.String()
}

