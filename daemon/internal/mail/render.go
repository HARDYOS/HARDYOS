func hasMailbox(c RootConfig, addr string) bool {
	for _, m := range c.Mailboxes {
		if m.Address == addr {
			return true
		}
	}
	return false
}

// mergeKeys joins the values of repeated keys (sorted input) with commas.
func mergeKeys(in [][2]string) [][2]string {
	var out [][2]string
	for _, kv := range in {
		if n := len(out); n > 0 && out[n-1][0] == kv[0] {
			out[n-1][1] += "," + kv[1]
			continue
		}
		out = append(out, kv)
	}
	return out
}

