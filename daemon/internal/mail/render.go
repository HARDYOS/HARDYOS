// File is one rendered configuration file.
type File struct {
	Path    string
	Content string
	Mode    uint32
	// Group owns the file (root owns every file); "" = root.
	Group string
}

// Env is what rendering needs to know about this server.
type Env struct {
	// MailRoot is the mountpoint of <pool>/mail.
	MailRoot string
	// VMailUID and VMailGID are hardyos-vmail's IDs.
	VMailUID, VMailGID int
	// NoIPv6: the kernel has IPv6 turned off (listening on :: would stop
	// Dovecot from starting).
	NoIPv6 bool
	// DovecotLog sends Dovecot's log to a file with authentication
	// debugging (tests); "" = syslog.
	DovecotLog string
}

func (e Env) listen() string {
	if e.NoIPv6 {
		return "*"
	}
	return "*, ::"
}

func (e Env) logSettings() string {
	if e.DovecotLog == "" {
		return "log_path = syslog\nsyslog_facility = mail"
	}
	return "log_path = " + e.DovecotLog + "\nauth_debug = yes"
}

func (e Env) inetProtocols() string {
	if e.NoIPv6 {
		return "ipv4"
	}
	return "all"
}

// Paths under MailRoot.
func (e Env) VMailDir() string    { return path.Join(e.MailRoot, "vmail") }
func (e Env) KeysDir() string     { return path.Join(e.MailRoot, "keys") }
func (e Env) DKIMDir() string     { return path.Join(e.MailRoot, "keys", "dkim") }
func (e Env) TLSDir() string      { return path.Join(e.MailRoot, "keys", "tls") }
func (e Env) TLSKey() string      { return path.Join(e.TLSDir(), "key.pem") }
func (e Env) TLSChain() string    { return path.Join(e.TLSDir(), "fullchain.pem") }
func (e Env) RadicaleDir() string { return path.Join(e.MailRoot, "radicale") }

// DKIMKeyPath is where a domain's DKIM private key is kept.
func (e Env) DKIMKeyPath(domain, selector string) string {
	return path.Join(e.DKIMDir(), domain+"."+selector+".key")
}

