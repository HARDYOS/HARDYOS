// The VPS (decision 231). Mail from the internet arrives at the VPS's
// Postfix on port 25, which relays it to HardyOS over NetBird and queues
// it for up to 14 days while home is offline (it accepts only recipients
// it has verified with HardyOS before: address verification, cached for a
// month). Mail apps on the internet reach IMAP and submission through
// HAProxy on the VPS, a plain TCP forwarder that passes the client's
// address on with the PROXY protocol; TLS ends at home, so the VPS never
// sees a password or a message in clear (except mail arriving on port 25,
// which the internet sends to it anyway).

// VPSSetup is what the VPS script is made from.
type VPSSetup struct {
	Hostname     string   // mail.<base>
	HomePeer     string   // HardyOS's NetBird address
	Domains      []string // relayed domains
	MaxMessageMB int
	// CertPath / KeyPath: a trusted certificate on the VPS for port 25
	// (optional; certbot's path); the script falls back to the snakeoil
	// certificate (opportunistic TLS, fine unless MTA-STS is enforced).
	CertPath string
	KeyPath  string
}

// VPSScript is the shell script to run once (and after every change of
// domains) on the VPS as root. It is idempotent, keeps backups of what it
// replaces, and touches only Postfix and HAProxy.
func VPSScript(v VPSSetup) (string, error) {
	if !ValidDomain(v.Hostname) {
		return "", invalid("set the mail server's name first")
	}
	peer, err := netip.ParseAddr(v.HomePeer)
	if err != nil {
		return "", invalid("this server isn't on NetBird yet (Control Panel › Remote Access)")
	}
	if len(v.Domains) == 0 {
		return "", invalid("add a mail domain first")
	}
	doms := append([]string(nil), v.Domains...)
	sort.Strings(doms)
	for _, d := range doms {
		if !ValidDomain(d) {
			return "", invalid("%q isn't a valid domain", d)
		}
	}
	if v.MaxMessageMB <= 0 {
		v.MaxMessageMB = DefaultMessageMB
	}
	home := peer.String()
	if peer.Is6() {
		home = "[" + home + "]"
	}
	var transport strings.Builder
	for _, d := range doms {
		fmt.Fprintf(&transport, "%s smtp:%s:%d\n", d, bracket(peer), PortRelay)
	}
	cert, key := "/etc/ssl/certs/ssl-cert-snakeoil.pem", "/etc/ssl/private/ssl-cert-snakeoil.key"
	if v.CertPath != "" && v.KeyPath != "" {
		cert, key = v.CertPath, v.KeyPath
	}
	script := fmt.Sprintf(`#!/bin/bash
# HardyOS mail relay for %[1]s
#
# Run as root on the VPS (Debian or Ubuntu). It installs Postfix (port 25:
# receives mail for your domains and relays it to HardyOS over NetBird,
# queueing it while home is offline) and HAProxy (ports 993, 465, 587:
# forwards mail apps to HardyOS with the PROXY protocol; TLS ends at home).
# It changes nothing else, keeps a backup of every file it replaces, and can
# be run again whenever HardyOS says the domains changed.
#
# Generated by HardyOS (Control Panel › Mail › VPS). Domains: %[2]s
set -euo pipefail

HOME_PEER=%[3]q        # HardyOS's NetBird address
MAIL_HOST=%[1]q
STAMP=$(date +%%Y%%m%%d%%H%%M%%S)

[ "$(id -u)" = 0 ] || { echo "Run this as root (sudo bash $0)." >&2; exit 1; }
command -v apt-get >/dev/null || { echo "This script is for Debian or Ubuntu." >&2; exit 1; }

echo "== Checking that HardyOS answers over NetBird ($HOME_PEER)"
if ! timeout 5 bash -c "exec 3<>/dev/tcp/$HOME_PEER/%[4]d" 2>/dev/null; then
  echo "   HardyOS doesn't answer on $HOME_PEER:%[4]d yet. Is NetBird up on both, and is the mail server on in HardyOS?" >&2
  echo "   Continuing; mail will wait in the queue until it does." >&2
fi

echo "== Installing Postfix and HAProxy"
export DEBIAN_FRONTEND=noninteractive
echo "postfix postfix/main_mailer_type select No configuration" | debconf-set-selections
echo "postfix postfix/mailname string $MAIL_HOST" | debconf-set-selections
apt-get update -qq
apt-get install -y -qq postfix haproxy ssl-cert >/dev/null

backup() { [ -f "$1" ] && cp -a "$1" "$1.hardyos-$STAMP" || true; }
backup /etc/postfix/main.cf
backup /etc/postfix/hardyos-transport
backup /etc/haproxy/haproxy.cfg

echo "== Postfix: relay for your domains to HardyOS"
echo "$MAIL_HOST" > /etc/mailname
cat > /etc/postfix/hardyos-transport <<'TRANSPORT'
%[5]sTRANSPORT
cat > /etc/postfix/main.cf <<'MAINCF'
# HardyOS mail relay (generated; changes are overwritten by the next run).
compatibility_level = 3.6
myhostname = %[1]s
myorigin = $myhostname
mydestination =
local_recipient_maps =
alias_maps =
alias_database =
# Nothing relays because of its address: only mail for the domains below
# is accepted, and only for addresses HardyOS confirmed exist.
mynetworks = 127.0.0.0/8 [::1]/128
inet_interfaces = all
inet_protocols = all
relay_domains = %[6]s
transport_maps = texthash:/etc/postfix/hardyos-transport
smtpd_banner = $myhostname ESMTP
disable_vrfy_command = yes
biff = no
append_dot_mydomain = no
message_size_limit = %[7]d
smtpd_helo_required = yes
smtpd_relay_restrictions = reject_unauth_destination
smtpd_recipient_restrictions = reject_non_fqdn_recipient, reject_unknown_recipient_domain, reject_unauth_destination, reject_unverified_recipient
smtpd_data_restrictions = reject_unauth_pipelining
# Recipients are checked with HardyOS (and remembered for a month), so
# mail for people who exist still queues here while home is offline.
address_verify_positive_expire_time = 31d
address_verify_positive_refresh_time = 7d
unverified_recipient_reject_code = 550
unverified_recipient_defer_code = 450
unverified_recipient_tempfail_action = defer
# Mail waits up to 14 days for home to come back.
maximal_queue_lifetime = 14d
bounce_queue_lifetime = 14d
# TLS for senders (opportunistic) and to HardyOS (inside WireGuard).
smtpd_tls_chain_files = %[8]s, %[9]s
smtpd_tls_security_level = may
smtpd_tls_protocols = >=TLSv1.2
smtpd_tls_received_header = yes
smtp_tls_security_level = may
smtp_tls_loglevel = 1
# Limits per sender address.
smtpd_client_connection_rate_limit = 60
smtpd_client_message_rate_limit = 120
anvil_rate_time_unit = 60s
MAINCF
# Take port 25 back from anything else HardyOS's script put there before.
postconf -M smtp/inet="smtp inet n - y - - smtpd" >/dev/null
postfix check
systemctl enable --now postfix >/dev/null
systemctl reload postfix

echo "== HAProxy: mail apps (993, 465, 587) to HardyOS"
cat > /etc/haproxy/haproxy.cfg <<'HAPROXY'
# HardyOS mail forwarder (generated; changes are overwritten by the next run).
global
    log /dev/log local0
    user haproxy
    group haproxy
    daemon
    maxconn 2000

defaults
    log global
    mode tcp
    option tcplog
    timeout connect 10s
    timeout client 30m
    timeout server 30m

frontend imaps
    bind :::993 v4v6
    default_backend hardyos_imaps
frontend submissions
    bind :::465 v4v6
    default_backend hardyos_submissions
frontend submission
    bind :::587 v4v6
    default_backend hardyos_submission

backend hardyos_imaps
    server home %[10]s:%[11]d send-proxy-v2 check inter 30s
backend hardyos_submissions
    server home %[10]s:%[12]d send-proxy-v2 check inter 30s
backend hardyos_submission
    server home %[10]s:%[13]d send-proxy-v2 check inter 30s
HAPROXY
haproxy -c -f /etc/haproxy/haproxy.cfg >/dev/null
systemctl enable --now haproxy >/dev/null
systemctl reload haproxy

if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  echo "== Opening ports 25, 465, 587 and 993 in ufw"
  ufw allow 25,465,587,993/tcp >/dev/null
fi

echo
echo "Done. Also open TCP 25, 465, 587 and 993 in your cloud provider's firewall."
echo "Then press Check in HardyOS (Control Panel > Mail > VPS)."
`, v.Hostname, strings.Join(doms, " "), peer.String(), PortRelay, transport.String(), strings.Join(doms, " "),
		int64(v.MaxMessageMB)<<20, key, cert, home, PortProxyIMAPS, PortProxySubms, PortProxySubm)
	return script, nil
}

// bracket is a Postfix next-hop address.
func bracket(a netip.Addr) string {
	if a.Is6() {
		return "[ipv6:" + a.String() + "]"
	}
	return "[" + a.String() + "]"
}

// fingerprint is a certificate's SHA-256 (hex).
func fingerprint(der []byte) string {
	h := sha256.Sum256(der)
	return hex.EncodeToString(h[:])
}

// VPSCheck is one step of checking the VPS from HardyOS.
type VPSCheck struct {
	Name   string `json:"name"`
	OK     bool   `json:"ok"`
	Detail string `json:"detail"`
}

// Dialer is what the VPS checks connect with (tests replace it).
type Dialer interface {
	DialContext(ctx context.Context, network, address string) (net.Conn, error)
}

// CheckVPS tests the VPS from the outside the way the internet sees it:
// port 25 answers as the mail server and relays to HardyOS (an address
// verification probe: Postfix on the VPS asks HardyOS whether a made-up
// address exists, so its answer shows whether the path home works), and
// ports 993 and 465 reach HardyOS's own TLS certificate.
func CheckVPS(ctx context.Context, d Dialer, publicIP, hostname, domain, leafFingerprint string) []VPSCheck {
	if d == nil {
		d = &net.Dialer{Timeout: 10 * time.Second}
	}
	var out []VPSCheck
	addr := func(port int) string { return net.JoinHostPort(publicIP, strconv.Itoa(port)) }

	// Port 25.
	c := VPSCheck{Name: "Port 25 (mail from the internet)"}
	func() {
		ctx, cancel := context.WithTimeout(ctx, 40*time.Second)
		defer cancel()
		conn, err := d.DialContext(ctx, "tcp", addr(25))
		if err != nil {
			c.Detail = "can't connect: " + err.Error() + ". Is port 25 open in the VPS's firewall? Some providers block it until you ask."
			return
		}
		defer conn.Close()
		deadline, _ := ctx.Deadline()
		_ = conn.SetDeadline(deadline)
		br := bufio.NewReader(conn)
		code, msg, err := readReply(br)
		if err != nil || code != 220 {
			c.Detail = fmt.Sprintf("no mail server greeting (%d %s %v)", code, msg, err)
			return
		}
		if !strings.Contains(strings.ToLower(msg), strings.ToLower(hostname)) {
			c.Detail = "a mail server answers, but not as " + hostname + ": " + clipText(msg, 120)
			return
		}
		probe := "hardyos-check-" + randomHex(6) + "@" + domain
		steps := []struct {
			cmd  string
			want int
		}{{"EHLO hardyos-check.invalid", 250}, {"MAIL FROM:<>", 250}, {"RCPT TO:<" + probe + ">", 0}}
		for _, s := range steps {
			fmt.Fprintf(conn, "%s\r\n", s.cmd)
			code, msg, err = readReply(br)
			if err != nil {
				c.Detail = "the conversation broke off: " + err.Error()
				return
			}
			if s.want != 0 && code != s.want {
				c.Detail = fmt.Sprintf("%s was answered %d %s", strings.Fields(s.cmd)[0], code, clipText(msg, 200))
				return
			}
		}
		fmt.Fprintf(conn, "QUIT\r\n")
		low := strings.ToLower(msg)
		switch {
		case code == 550 && (strings.Contains(low, "unknown") || strings.Contains(low, "rejected") || strings.Contains(low, "unverified")):
			// HardyOS answered "no such mailbox": the whole path works.
			c.OK, c.Detail = true, "the VPS receives mail for "+domain+" and reached HardyOS to check an address"
		case code == 450 || code == 451:
			c.Detail = "the VPS couldn't reach HardyOS over NetBird to check an address: " + clipText(msg, 200)
		case code == 554 && strings.Contains(low, "relay"):
			c.Detail = "the VPS doesn't relay " + domain + " yet: run the script again after adding the domain"
		default:
			c.Detail = fmt.Sprintf("unexpected answer %d %s", code, clipText(msg, 200))
		}
	}()
	out = append(out, c)

	for _, p := range []struct {
		name string
		port int
	}{{"Port 993 (IMAP for mail apps)", 993}, {"Port 465 (sending from mail apps)", 465}} {
		c := VPSCheck{Name: p.name}
		func() {
			ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
			defer cancel()
			raw, err := d.DialContext(ctx, "tcp", addr(p.port))
			if err != nil {
				c.Detail = "can't connect: " + err.Error()
				return
			}
			defer raw.Close()
			var leaf []byte
			tc := tls.Client(raw, &tls.Config{ServerName: hostname, InsecureSkipVerify: true, //nolint:gosec // compared by fingerprint below
				VerifyConnection: func(cs tls.ConnectionState) error {
					if len(cs.PeerCertificates) > 0 {
						leaf = cs.PeerCertificates[0].Raw
					}
					return nil
				}})
			if err := tc.HandshakeContext(ctx); err != nil {
				c.Detail = "no TLS from HardyOS through the VPS: " + err.Error()
				return
			}
			if leafFingerprint != "" && fingerprint(leaf) != leafFingerprint {
				c.Detail = "TLS works but the certificate isn't this server's: is the VPS forwarding to another server?"
				return
			}
			c.OK, c.Detail = true, "forwarded to HardyOS (its certificate answered)"
		}()
		out = append(out, c)
	}
	return out
}

func randomHex(n int) string {
	b := make([]byte, n)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

// readReply reads one (possibly multi-line) SMTP reply.
func readReply(br *bufio.Reader) (int, string, error) {
	var msg []string
	for i := 0; i < 100; i++ {
		line, err := br.ReadString('\n')
		if err != nil {
			return 0, strings.Join(msg, " "), err
		}
		if len(line) > 4096 {
			line = line[:4096]
		}
		line = strings.TrimRight(line, "\r\n")
		if len(line) < 3 {
			return 0, line, fmt.Errorf("malformed reply %q", line)
		}
		code, err := strconv.Atoi(line[:3])
		if err != nil {
			return 0, line, fmt.Errorf("malformed reply %q", line)
		}
		if len(line) > 4 {
			msg = append(msg, line[4:])
		}
		if len(line) == 3 || line[3] == ' ' {
			return code, strings.Join(msg, " "), nil
		}
	}
	return 0, "", fmt.Errorf("reply too long")
}
