package nfs

// Cluster exports (docs/plans/cluster.md section 5.3): the storage node
// exports VM state and app data to their owner's storage address only
// (no_root_squash; the export is exclusive), and cluster shared folders to
// every active compute node (root_squash). They live in their own file, so
// the LAN shares' file (Manager) and this one never step on each other.
// Root renders the file from a validated list; every path, fsid and client
// is checked again by ValidateCluster before it is written.

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"log/slog"
	"net/netip"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
	"sync"

	"github.com/hardyos/hardyos/daemon/internal/sysexec"
)

// ClusterExportsFile holds the cluster exports.
const ClusterExportsFile = "/etc/exports.d/hardyos-cluster.exports"

// ClusterConfFile lowers nfsd's NFSv4 lease and grace times, so a storage
// node reboot blocks opens for seconds, not 90.
const ClusterConfFile = "/etc/nfs.conf.d/hardyos-cluster.conf"

// LeaseSeconds is the lease and grace time on a storage node.
const LeaseSeconds = 15

// Cluster export kinds (cluster.ExportKind's values).
const (
	KindVMState = "vmstate"
	KindAppData = "appdata"
	KindShare   = "share"
)

// ClusterExport is one dataset exported to compute nodes.
type ClusterExport struct {
	Kind    string `json:"kind"`
	Dataset string `json:"dataset"`
	// Path is the dataset's mountpoint (checked by root).
	Path string `json:"path"`
	// GUID is the dataset's ZFS GUID; the export's fsid derives from it so
	// it never changes across reboots or pool imports.
	GUID string `json:"guid"`
	// Clients are storage network addresses: exactly one (two during a
	// live migration) for VM state and app data, the active compute nodes
	// for shares.
	Clients []netip.Addr `json:"clients"`
}

// FSID is the export's fsid (a UUID derived from the dataset's GUID).
func FSID(guid string) string {
	sum := sha256.Sum256([]byte("hardyos-fsid\x00" + guid))
	h := hex.EncodeToString(sum[:16])
	return h[0:8] + "-" + h[8:12] + "-" + h[12:16] + "-" + h[16:20] + "-" + h[20:32]
}

var guidRE = regexp.MustCompile(`^[0-9]{1,20}$`)

func clusterOptions(e ClusterExport) string {
	squash := "no_root_squash"
	if e.Kind == KindShare {
		squash = "root_squash"
	}
	return "rw,sync,no_subtree_check," + squash + ",sec=sys,fsid=" + FSID(e.GUID)
}

// checkClusterExport validates one export.
func checkClusterExport(e ClusterExport) error {
	if err := ValidPath(e.Path); err != nil {
		return err
	}
	if !guidRE.MatchString(e.GUID) {
		return fmt.Errorf("%s: %q isn't a dataset GUID", e.Dataset, e.GUID)
	}
	if len(e.Clients) == 0 {
		return fmt.Errorf("%s has no clients", e.Dataset)
	}
	parts := strings.Split(e.Dataset, "/")
	switch e.Kind {
	case KindVMState:
		if len(parts) != 3 || parts[1] != "vms" {
			return fmt.Errorf("%q isn't a VM's dataset", e.Dataset)
		}
		if len(e.Clients) > 2 {
			return fmt.Errorf("%s may be exported to one node (two during a live migration)", e.Dataset)
		}
	case KindAppData:
		if len(parts) != 3 || parts[1] != "apps" {
			return fmt.Errorf("%q isn't an app's dataset", e.Dataset)
		}
		if len(e.Clients) > 2 {
			return fmt.Errorf("%s may be exported to one node (two during a live migration)", e.Dataset)
		}
	case KindShare:
		if len(parts) != 3 || parts[1] != "shares" {
			return fmt.Errorf("%q isn't a shared folder", e.Dataset)
		}
	default:
		return fmt.Errorf("export kind %q isn't vmstate, appdata or share", e.Kind)
	}
	for _, c := range e.Clients {
		if !c.Is4() || c.IsUnspecified() || c.IsLoopback() || c.IsMulticast() {
			return fmt.Errorf("%s: client %s isn't a storage network address", e.Dataset, c)
		}
	}
	return nil
}

const clusterHeader = "# Generated by HardyOS (hardyd-priv): cluster exports on the storage network.\n# Changes made here are overwritten.\n"

// RenderCluster renders the cluster exports file.
func RenderCluster(exports []ClusterExport) (string, error) {
	l := slices.Clone(exports)
	sort.Slice(l, func(i, j int) bool { return l[i].Path < l[j].Path })
	var b strings.Builder
	b.WriteString(clusterHeader)
	paths := map[string]bool{}
	for _, e := range l {
		if err := checkClusterExport(e); err != nil {
			return "", err
		}
		if paths[e.Path] {
			return "", fmt.Errorf("%s is exported twice", e.Path)
		}
		paths[e.Path] = true
		cl := slices.Clone(e.Clients)
		slices.SortFunc(cl, func(a, b netip.Addr) int { return a.Compare(b) })
		cl = slices.Compact(cl)
		b.WriteString(e.Path)
		for _, c := range cl {
			fmt.Fprintf(&b, " %s(%s)", c, clusterOptions(e))
		}
		b.WriteByte('\n')
	}
	return b.String(), nil
}

var clusterOptRE = regexp.MustCompile(`^rw,sync,no_subtree_check,(no_root_squash|root_squash),sec=sys,fsid=[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// ValidateCluster checks a rendered cluster exports file against the
// exports it was rendered from: only their paths, single IPv4 clients
// with exactly the options RenderCluster writes, no_root_squash only on
// exports whose kind is a VM's state or an app's data and root_squash on
// shares (the export's kind decides, never its path; L4), and at most two
// clients of an owner-only export.
func ValidateCluster(content string, exports []ClusterExport) error {
	kinds := map[string]string{}
	for _, e := range exports {
		kinds[e.Path] = e.Kind
	}
	for i, line := range strings.Split(strings.TrimSuffix(content, "\n"), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, " ")
		if len(f) < 2 || ValidPath(f[0]) != nil {
			return fmt.Errorf("cluster exports line %d: bad path", i+1)
		}
		kind, known := kinds[f[0]]
		if !known {
			return fmt.Errorf("cluster exports line %d: %s isn't one of the exports", i+1, f[0])
		}
		if kind != KindShare && len(f)-1 > 2 {
			return fmt.Errorf("cluster exports line %d: an owner-only export has more than two clients", i+1)
		}
		for _, c := range f[1:] {
			spec, opts, ok := strings.Cut(c, "(")
			if !ok || !strings.HasSuffix(opts, ")") {
				return fmt.Errorf("cluster exports line %d: bad client %q", i+1, c)
			}
			a, err := netip.ParseAddr(spec)
			if err != nil || !a.Is4() || a.IsUnspecified() {
				return fmt.Errorf("cluster exports line %d: client %q isn't one address", i+1, spec)
			}
			m := clusterOptRE.FindStringSubmatch(strings.TrimSuffix(opts, ")"))
			if m == nil {
				return fmt.Errorf("cluster exports line %d: unexpected options %q", i+1, opts)
			}
			owner := kind == KindVMState || kind == KindAppData
			if m[1] == "no_root_squash" && !owner {
				return fmt.Errorf("cluster exports line %d: a shared folder can't be exported without root_squash", i+1)
			}
			if m[1] == "root_squash" && owner {
				return fmt.Errorf("cluster exports line %d: unexpected root_squash on a VM's or app's own data", i+1)
			}
		}
	}
	return nil
}

// HasClusterExports reports whether the cluster exports file (under root)
// exports anything, so the LAN shares' manager keeps the NFS server
// running for them.
func HasClusterExports(root string) bool {
	b, err := os.ReadFile(filepath.Join(root, ClusterExportsFile))
	if err != nil {
		return false
	}
	for _, l := range strings.Split(string(b), "\n") {
		if l != "" && !strings.HasPrefix(l, "#") {
			return true
		}
	}
	return false
}

// ClusterManager writes the cluster exports on the storage node. It runs
// as root.
type ClusterManager struct {
	Runner sysexec.Runner
	Root   string // "/" in production
	Log    *slog.Logger

	mu sync.Mutex
}

func (m *ClusterManager) sys(p string) string {
	if m.Root == "" {
		return p
	}
	return filepath.Join(m.Root, p)
}

func (m *ClusterManager) log() *slog.Logger {
	if m.Log != nil {
		return m.Log
	}
	return slog.Default()
}

// Current returns the exported paths and their clients from the file.
func (m *ClusterManager) Current() map[string][]netip.Addr {
	out := map[string][]netip.Addr{}
	b, err := os.ReadFile(m.sys(ClusterExportsFile))
	if err != nil {
		return out
	}
	for _, line := range strings.Split(string(b), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, " ")
		for _, c := range f[1:] {
			spec, _, _ := strings.Cut(c, "(")
			if a, err := netip.ParseAddr(spec); err == nil {
				out[f[0]] = append(out[f[0]], a)
			}
		}
	}
	return out
}

// Apply writes the exports (validated), makes sure nfsd runs with the
// short lease, and re-exports; on failure the previous file is put back.
func (m *ClusterManager) Apply(ctx context.Context, exports []ClusterExport) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	content, err := RenderCluster(exports)
	if err != nil {
		return err
	}
	if err := ValidateCluster(content, exports); err != nil {
		return fmt.Errorf("refusing to write the cluster exports: %w", err)
	}
	if err := m.ensureConf(ctx); err != nil {
		return err
	}
	path := m.sys(ClusterExportsFile)
	old, rerr := os.ReadFile(path)
	if rerr == nil && string(old) == content {
		return nil
	}
	if err := writeAtomic(path, content); err != nil {
		return fmt.Errorf("writing %s: %w", ClusterExportsFile, err)
	}
	if len(exports) > 0 {
		if res, err := m.Runner.Run(ctx, nil, "systemctl", "is-active", "--quiet", Unit); err != nil || res.ExitCode != 0 {
			if _, err := sysexec.Output(ctx, m.Runner, "systemctl", "enable", "--now", Unit); err != nil {
				return fmt.Errorf("starting the NFS server: %w", err)
			}
		}
	}
	if _, err := sysexec.Output(ctx, m.Runner, "exportfs", "-ra"); err != nil {
		back := clusterHeader
		if rerr == nil {
			back = string(old)
		}
		_ = writeAtomic(path, back)
		_, _ = sysexec.Output(ctx, m.Runner, "exportfs", "-ra")
		return fmt.Errorf("exportfs: %w", err)
	}
	m.log().Info("nfs: cluster exports updated", "exports", len(exports))
	return nil
}

// ClusterConf is the storage node's nfsd settings: the short lease and
// grace times, and NFSv3 off (L6: cluster mounts are NFSv4.2 only, so
// mountd's and NLM's side protocols aren't served) unless the server's
// own LAN shares are exported over NFS (lanV3), which may use NFSv3.
func ClusterConf(lanV3 bool) string {
	s := fmt.Sprintf("# Generated by HardyOS (hardyd-priv): short NFSv4 lease for cluster storage.\n[nfsd]\nlease-time=%d\ngrace-time=%d\n", LeaseSeconds, LeaseSeconds)
	if !lanV3 {
		s += "vers3=n\n"
	}
	return s
}

// hasLANExports reports whether the LAN shares' exports file exports
// anything.
func hasLANExports(path string) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	for _, l := range strings.Split(string(b), "\n") {
		if l = strings.TrimSpace(l); l != "" && !strings.HasPrefix(l, "#") {
			return true
		}
	}
	return false
}

// ensureConf writes the lease and grace settings; nfsd reads them when it
// starts, so a running server is restarted once when they change.
func (m *ClusterManager) ensureConf(ctx context.Context) error {
	want := ClusterConf(hasLANExports(m.sys(ExportsFile)))
	p := m.sys(ClusterConfFile)
	if b, err := os.ReadFile(p); err == nil && string(b) == want {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	if err := writeAtomic(p, want); err != nil {
		return err
	}
	if res, err := m.Runner.Run(ctx, nil, "systemctl", "is-active", "--quiet", Unit); err == nil && res.ExitCode == 0 {
		if _, err := sysexec.Output(ctx, m.Runner, "systemctl", "restart", Unit); err != nil {
			return fmt.Errorf("restarting the NFS server for the cluster lease time: %w", err)
		}
	}
	return nil
}

// ExpireClients flushes the export cache and expires the NFSv4 clients
// connected from addrs (/proc/fs/nfsd/clients/*/ctl), so a fenced node's
// open state is gone at once rather than after its lease.
func (m *ClusterManager) ExpireClients(ctx context.Context, addrs []netip.Addr) (int, error) {
	var errs []error
	if _, err := sysexec.Output(ctx, m.Runner, "exportfs", "-f"); err != nil {
		errs = append(errs, err)
	}
	dir := m.sys("/proc/fs/nfsd/clients")
	ents, err := os.ReadDir(dir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return 0, errors.Join(errs...)
		}
		return 0, errors.Join(append(errs, err)...)
	}
	n := 0
	for _, e := range ents {
		info, err := os.ReadFile(filepath.Join(dir, e.Name(), "info"))
		if err != nil {
			continue
		}
		addr := clientAddress(string(info))
		if !addr.IsValid() || !slices.Contains(addrs, addr) {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, e.Name(), "ctl"), []byte("expire\n"), 0); err != nil {
			errs = append(errs, fmt.Errorf("expiring NFS client %s: %w", addr, err))
			continue
		}
		n++
	}
	return n, errors.Join(errs...)
}

// clientAddress reads `address: "10.77.0.21:861"` from a client's info.
func clientAddress(info string) netip.Addr {
	for _, l := range strings.Split(info, "\n") {
		v, ok := strings.CutPrefix(strings.TrimSpace(l), "address:")
		if !ok {
			continue
		}
		v = strings.Trim(strings.TrimSpace(v), `"`)
		if ap, err := netip.ParseAddrPort(v); err == nil {
			return ap.Addr().Unmap()
		}
		if a, err := netip.ParseAddr(v); err == nil {
			return a.Unmap()
		}
	}
	return netip.Addr{}
}
