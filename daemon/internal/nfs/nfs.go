// Package nfs shares shared folders with Linux and Unix computers over NFS
// (v3 and v4). It runs inside hardyd-priv. See docs/plans/file-sharing.md
// (section 2) and docs/shares.md.
//
// Every NFS client of a folder is squashed to one identity that only that
// folder uses (all_squash, anonuid=anongid=<uid> with a uid from
// 31000-31999 kept in the dataset property org.hardyos:nfs-uid), and that
// identity is given read or write on disk through the shared folders' ACL
// walker, like an app. So an NFS client can never act as root, as a domain
// user or as any other folder's identity, whatever user IDs it sends.
package nfs

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/netip"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"sync"
	"time"

	"github.com/hardyos/hardyos/daemon/internal/shares"
	"github.com/hardyos/hardyos/daemon/internal/sysexec"
	"github.com/hardyos/hardyos/daemon/internal/zfs"
)

// ExportsFile is generated by HardyOS; exportfs reads every *.exports file
// in /etc/exports.d next to /etc/exports.
const ExportsFile = "/etc/exports.d/hardyos.exports"

// Unit is the NFS server (Debian's nfs-kernel-server). It stays disabled
// until a folder is shared over NFS.
const Unit = "nfs-server.service"

// Shares is what NFS needs from the shared folders (*shares.Manager).
type Shares interface {
	List(ctx context.Context) ([]shares.Share, error)
	GrantNFS(ctx context.Context, id string, uid int, write bool) error
	RevokeNFS(ctx context.Context, id string, uid int) error
}

// Export is one shared folder offered over NFS.
type Export struct {
	Share   string           `json:"share"`
	Path    string           `json:"path"`
	UID     int              `json:"uid"`
	Clients []shares.NFSRule `json:"clients"`
}

// Status is what the NFS server is doing.
type Status struct {
	Running bool     `json:"running"`
	Exports []Export `json:"exports"`
	// UIDs maps every shared folder that has an NFS identity to it.
	UIDs map[string]int `json:"uids"`
	// Problem is the last sync's error, if it failed.
	Problem string `json:"problem,omitempty"`
}

// Manager keeps the exports, the NFS identities and the server in step
// with the shared folders' settings. It runs as root.
type Manager struct {
	Runner sysexec.Runner
	Shares Shares
	Log    *slog.Logger
	// Root prefixes system paths; "/" in production.
	Root string

	mu sync.Mutex
	// applied is the access given on disk in this process, by dataset:
	// "<uid>:<read|write>". Empty after a restart, so every exported folder
	// is walked once per start (the walker changes nothing that is right).
	applied map[string]string
	last    Status
}

func (m *Manager) log() *slog.Logger {
	if m.Log != nil {
		return m.Log
	}
	return slog.Default()
}

func (m *Manager) sys(p string) string {
	if m.Root == "" {
		return p
	}
	return filepath.Join(m.Root, p)
}

func (m *Manager) zfs(ctx context.Context, args ...string) ([]byte, error) {
	return sysexec.Output(ctx, m.Runner, "zfs", args...)
}

// syncInterval is how often Watch checks for pools that were imported or
// unlocked since (their folders come and go without a share change).
const syncInterval = 2 * time.Minute

// Watch syncs at start and then every couple of minutes until ctx is done.
func (m *Manager) Watch(ctx context.Context) {
	for {
		sctx, cancel := context.WithTimeout(ctx, 2*time.Minute)
		if err := m.Sync(sctx); err != nil {
			m.log().Warn("nfs: sync failed", "err", err)
		}
		cancel()
		select {
		case <-ctx.Done():
			return
		case <-time.After(syncInterval):
		}
	}
}

// Changed is the shared folders' after-change hook: it syncs and logs.
func (m *Manager) Changed(ctx context.Context) {
	if err := m.Sync(ctx); err != nil {
		m.log().Warn("nfs: sync after a shared folder change failed", "err", err)
	}
}

// Withdraw stops exporting one folder (before it is deleted: a file
// system the NFS server holds can't be unmounted). The next Sync puts it
// back if it still exists.
func (m *Manager) Withdraw(ctx context.Context, id string) error {
	return m.sync(ctx, id)
}

// Sync brings exports, identities and the server in line with the settings.
func (m *Manager) Sync(ctx context.Context) error { return m.sync(ctx, "") }

// Status reports the last sync and whether the server runs.
func (m *Manager) Status(ctx context.Context) Status {
	m.mu.Lock()
	st := m.last
	m.mu.Unlock()
	st.Running = m.active(ctx)
	if st.Exports == nil {
		st.Exports = []Export{}
	}
	if st.UIDs == nil {
		st.UIDs = map[string]int{}
	}
	return st
}

func (m *Manager) sync(ctx context.Context, skip string) (err error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	defer func() {
		m.last.Problem = ""
		if err != nil {
			m.last.Problem = err.Error()
		}
	}()
	got, err := m.Shares.List(ctx)
	if err != nil {
		return err
	}
	l := append([]shares.Share(nil), got...)
	sort.Slice(l, func(i, j int) bool { return l[i].Dataset < l[j].Dataset })
	have, err := m.readUIDs(ctx)
	if err != nil {
		return err
	}
	uids, set := AssignUIDs(l, have)
	var errs []error
	for _, s := range set {
		if zfs.ValidDatasetName(s.Dataset) != nil || s.Dataset != shares.Dataset(s.Pool, s.ID) {
			delete(uids, s.Dataset)
			continue
		}
		if _, err := m.zfs(ctx, "set", fmt.Sprintf("%s=%d", shares.PropNFSUID, uids[s.Dataset]), s.Dataset); err != nil {
			errs = append(errs, fmt.Errorf("recording %s's NFS identity: %w", s.Name, err))
			delete(uids, s.Dataset)
			continue
		}
		m.log().Info("nfs: identity given", "share", s.ID, "uid", uids[s.Dataset])
	}

	if m.applied == nil {
		m.applied = map[string]string{}
	}
	listed := map[string]bool{}
	var exports []Export
	for _, sh := range l {
		listed[sh.Dataset] = true
		uid, hasUID := uids[sh.Dataset]
		want := sh.Services.NFS.Enabled && sh.Mounted && hasUID && sh.ID != skip
		var sv shares.Services
		if want {
			if sv, err = shares.CheckServices(sh.Services); err != nil {
				m.log().Warn("nfs: a shared folder's NFS settings aren't valid; not sharing it", "share", sh.ID, "err", err)
				want = false
			} else if err := ValidPath(sh.Path); err != nil {
				m.log().Warn("nfs: a shared folder's path can't be exported; not sharing it", "share", sh.ID, "err", err)
				want = false
			}
		}
		prev := m.applied[sh.Dataset]
		if !want {
			if prev != "" && sh.Mounted && sh.ID != skip {
				// NFS was turned off: take the identity's access away.
				pu, _, _ := strings.Cut(prev, ":")
				if n, err := strconv.Atoi(pu); err == nil {
					if err := m.Shares.RevokeNFS(ctx, sh.ID, n); err != nil {
						errs = append(errs, err)
						continue
					}
				}
				delete(m.applied, sh.Dataset)
			}
			continue
		}
		write := false
		for _, c := range sv.NFS.Clients {
			write = write || c.Access == shares.LevelWrite
		}
		key := fmt.Sprintf("%d:%s", uid, levelName(write))
		if prev != key {
			if pu, _, _ := strings.Cut(prev, ":"); prev != "" && pu != strconv.Itoa(uid) {
				if n, err := strconv.Atoi(pu); err == nil {
					_ = m.Shares.RevokeNFS(ctx, sh.ID, n) // the folder got another identity
				}
			}
			if err := m.Shares.GrantNFS(ctx, sh.ID, uid, write); err != nil {
				errs = append(errs, err)
				delete(m.applied, sh.Dataset)
				continue // not exported until its identity has access
			}
			m.applied[sh.Dataset] = key
		}
		exports = append(exports, Export{Share: sh.ID, Path: sh.Path, UID: uid, Clients: sv.NFS.Clients})
	}
	for ds := range m.applied {
		if !listed[ds] {
			delete(m.applied, ds)
		}
	}
	m.last.Exports = exports
	m.last.UIDs = map[string]int{}
	for _, sh := range l {
		if u, ok := uids[sh.Dataset]; ok {
			m.last.UIDs[sh.ID] = u
		}
	}
	if err := m.apply(ctx, exports); err != nil {
		errs = append(errs, err)
	}
	return errors.Join(errs...)
}

func levelName(write bool) string {
	if write {
		return shares.LevelWrite
	}
	return shares.LevelRead
}

// readUIDs returns the NFS identities set on datasets (locally, never
// inherited), by dataset.
func (m *Manager) readUIDs(ctx context.Context) (map[string]int, error) {
	out, err := m.zfs(ctx, "get", "-H", "-p", "-t", "filesystem", "-s", "local", "-o", "name,value", shares.PropNFSUID)
	if err != nil {
		return nil, fmt.Errorf("reading the NFS identities: %w", err)
	}
	res := map[string]int{}
	for _, line := range strings.Split(string(out), "\n") {
		ds, v, ok := strings.Cut(line, "\t")
		if !ok {
			continue
		}
		if n, err := strconv.Atoi(strings.TrimSpace(v)); err == nil && shares.ValidNFSUID(n) == nil {
			res[ds] = n
		}
	}
	return res, nil
}

// AssignUIDs decides every folder's NFS identity. Folders keep the one
// they have unless another folder already uses it (two pools from
// different servers imported together): folders with NFS on keep theirs
// first, then the rest, in dataset order. Folders with NFS on (and
// mounted) that have none, or lost theirs to a clash, get the lowest free
// one. set lists the folders whose property must be written.
func AssignUIDs(l []shares.Share, have map[string]int) (uids map[string]int, set []shares.Share) {
	uids = map[string]int{}
	used := map[int]bool{}
	for _, pass := range []bool{true, false} {
		for _, sh := range l {
			u, ok := have[sh.Dataset]
			if !ok || sh.Services.NFS.Enabled != pass || used[u] {
				continue
			}
			used[u] = true
			uids[sh.Dataset] = u
		}
	}
	next := shares.FirstNFSUID
	for _, sh := range l {
		if _, ok := uids[sh.Dataset]; ok || !sh.Services.NFS.Enabled || !sh.Mounted {
			continue
		}
		for next <= shares.LastNFSUID && used[next] {
			next++
		}
		if next > shares.LastNFSUID {
			break // a thousand folders shared over NFS: the rest wait
		}
		used[next] = true
		uids[sh.Dataset] = next
		set = append(set, sh)
	}
	return uids, set
}

// ---- the exports file ------------------------------------------------------

const header = "# Generated by HardyOS (hardyd-priv) from the shared folders' NFS settings.\n# Changes made here are overwritten.\n"

var pathRE = regexp.MustCompile(`^(/[A-Za-z0-9][A-Za-z0-9._-]*)+$`)

// ValidPath accepts an absolute, clean path of plain names (shared folders
// live at /mnt/<pool>/shares/<id>), so it needs no quoting in exports(5).
func ValidPath(p string) error {
	if !pathRE.MatchString(p) || filepath.Clean(p) != p || len(p) > 1024 {
		return fmt.Errorf("%q can't be exported over NFS", p)
	}
	for _, part := range strings.Split(p[1:], "/") {
		if part == "." || part == ".." {
			return fmt.Errorf("%q can't be exported over NFS", p)
		}
	}
	return nil
}

// options for every client; rw or ro is put in front.
func options(uid int) string {
	// sync: writes are on disk before the client is told they are.
	// insecure: clients may use unprivileged ports (macOS Finder does);
	// with all_squash a privileged port proves nothing anyway.
	return fmt.Sprintf("sync,no_subtree_check,all_squash,anonuid=%d,anongid=%d,sec=sys,insecure", uid, uid)
}

// Render writes the exports file. Clients are checked again; single
// addresses come before networks and longer prefixes before shorter ones,
// so the most specific rule is the one the NFS server uses for a computer.
func Render(exports []Export) (string, error) {
	var b strings.Builder
	b.WriteString(header)
	for _, e := range exports {
		if err := ValidPath(e.Path); err != nil {
			return "", err
		}
		if err := shares.ValidNFSUID(e.UID); err != nil {
			return "", err
		}
		type client struct {
			spec   string
			prefix netip.Prefix
			access string
		}
		var cl []client
		for _, c := range e.Clients {
			p, err := clientPrefix(c.Client)
			if err != nil {
				return "", err
			}
			if c.Access != shares.LevelRead && c.Access != shares.LevelWrite {
				return "", fmt.Errorf("NFS access %q for %s isn't read or write", c.Access, c.Client)
			}
			spec := p.String()
			if p.IsSingleIP() {
				spec = p.Addr().String()
			}
			cl = append(cl, client{spec, p, c.Access})
		}
		if len(cl) == 0 {
			continue
		}
		sort.SliceStable(cl, func(i, j int) bool {
			a, c := cl[i].prefix, cl[j].prefix
			if a.IsSingleIP() != c.IsSingleIP() {
				return a.IsSingleIP()
			}
			if !a.IsSingleIP() && a.Bits() != c.Bits() {
				return a.Bits() > c.Bits()
			}
			return cl[i].spec < cl[j].spec
		})
		b.WriteString(e.Path)
		for _, c := range cl {
			mode := "ro"
			if c.access == shares.LevelWrite {
				mode = "rw"
			}
			fmt.Fprintf(&b, " %s(%s,%s)", c.spec, mode, options(e.UID))
		}
		b.WriteByte('\n')
	}
	return b.String(), nil
}

// clientPrefix parses an address or network (never every address).
func clientPrefix(c string) (netip.Prefix, error) {
	var p netip.Prefix
	if strings.Contains(c, "/") {
		var err error
		if p, err = netip.ParsePrefix(c); err != nil {
			return p, fmt.Errorf("%q isn't an address or network", c)
		}
		p = p.Masked()
	} else {
		a, err := netip.ParseAddr(c)
		if err != nil || a.Zone() != "" {
			return p, fmt.Errorf("%q isn't an address or network", c)
		}
		a = a.Unmap()
		p = netip.PrefixFrom(a, a.BitLen())
	}
	if p.Bits() == 0 || p.Addr().IsUnspecified() && p.IsSingleIP() {
		return p, fmt.Errorf("%q would let every computer in", c)
	}
	return p, nil
}

// Validate checks a rendered exports file line by line before it is
// written: only our header comments, and lines of a valid path followed by
// clients with exactly the options Render writes.
func Validate(content string) error {
	optRE := regexp.MustCompile(`^(r[ow]),sync,no_subtree_check,all_squash,anonuid=(3[01][0-9]{3}),anongid=(3[01][0-9]{3}),sec=sys,insecure$`)
	for i, line := range strings.Split(strings.TrimSuffix(content, "\n"), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, " ")
		if len(f) < 2 || ValidPath(f[0]) != nil {
			return fmt.Errorf("exports line %d: bad path", i+1)
		}
		for _, c := range f[1:] {
			spec, opts, ok := strings.Cut(c, "(")
			if !ok || !strings.HasSuffix(opts, ")") {
				return fmt.Errorf("exports line %d: bad client %q", i+1, c)
			}
			if _, err := clientPrefix(spec); err != nil {
				return fmt.Errorf("exports line %d: %w", i+1, err)
			}
			m := optRE.FindStringSubmatch(strings.TrimSuffix(opts, ")"))
			if m == nil || m[2] != m[3] {
				return fmt.Errorf("exports line %d: unexpected options %q", i+1, opts)
			}
			if n, _ := strconv.Atoi(m[2]); shares.ValidNFSUID(n) != nil {
				return fmt.Errorf("exports line %d: user ID %s outside the NFS range", i+1, m[2])
			}
		}
	}
	return nil
}

// apply writes the exports file if it changed, tells the server, and
// runs the server only while something is exported.
func (m *Manager) apply(ctx context.Context, exports []Export) error {
	content, err := Render(exports)
	if err != nil {
		return err
	}
	if err := Validate(content); err != nil {
		return fmt.Errorf("refusing to write the exports file: %w", err)
	}
	path := m.sys(ExportsFile)
	old, rerr := os.ReadFile(path)
	changed := rerr != nil || string(old) != content
	if changed {
		if err := writeAtomic(path, content); err != nil {
			return fmt.Errorf("writing %s: %w", ExportsFile, err)
		}
	}
	active := m.active(ctx)
	if len(exports) > 0 {
		if !active || !m.enabled(ctx) {
			// Starting it exports everything (its unit runs exportfs -r).
			// --no-block: at boot it waits for the network, which comes up
			// after hardyd-priv.
			if _, err := sysexec.Output(ctx, m.Runner, "systemctl", "enable", "--now", "--no-block", Unit); err != nil {
				return fmt.Errorf("starting the NFS server: %w", err)
			}
			m.log().Info("nfs: server enabled", "exports", len(exports))
		}
	}
	if changed && active {
		if err := m.exportfs(ctx); err != nil {
			// Put the previous file back (or an empty one) so the server
			// keeps a working table and the next sync tries again.
			back := header
			if rerr == nil {
				back = string(old)
			}
			_ = writeAtomic(path, back)
			_ = m.exportfs(ctx)
			return err
		}
		m.log().Info("nfs: exports updated", "exports", len(exports))
	}
	if len(exports) == 0 && active {
		if _, err := sysexec.Output(ctx, m.Runner, "systemctl", "disable", "--now", "--no-block", Unit); err != nil {
			return fmt.Errorf("stopping the NFS server: %w", err)
		}
		m.log().Info("nfs: nothing is shared over NFS; server stopped")
	}
	return nil
}

func (m *Manager) exportfs(ctx context.Context) error {
	if _, err := sysexec.Output(ctx, m.Runner, "exportfs", "-ra"); err != nil {
		return fmt.Errorf("exportfs: %w", err)
	}
	return nil
}

func (m *Manager) active(ctx context.Context) bool {
	res, err := m.Runner.Run(ctx, nil, "systemctl", "is-active", "--quiet", Unit)
	return err == nil && res.ExitCode == 0
}

func (m *Manager) enabled(ctx context.Context) bool {
	res, err := m.Runner.Run(ctx, nil, "systemctl", "is-enabled", "--quiet", Unit)
	return err == nil && res.ExitCode == 0
}

// writeAtomic replaces path with content (0644): a temporary file in the
// same folder (not named *.exports, so exportfs never reads it half
// written), synced, then renamed over it.
func writeAtomic(path, content string) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, ".hardyos-exports-*.tmp")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if _, err := f.WriteString(content); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(0o644); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// ShareUID returns a folder's NFS identity from the last sync (0 = none).
func (m *Manager) ShareUID(id string) int {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.last.UIDs[id]
}
