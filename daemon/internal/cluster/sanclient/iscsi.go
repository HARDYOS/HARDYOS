// iscsiadm exit codes that aren't failures for us.
const (
	iscsiSessionExists = 15 // login: already logged in
	iscsiNoObjects     = 21 // logout / session list: nothing there
)

// ReplacementTimeout is how long I/O waits for a lost session before
// failing (QEMU then pauses the VM: error_policy=stop).
const ReplacementTimeout = 15

// NOPInterval is the NOP-Out interval and timeout (seconds).
const NOPInterval = 5

// InitiatorArgs is sanclient.initiator.set.
type InitiatorArgs = SessionArgs

// SetInitiator writes this node's initiator name (iSCSI's own file) and
// restarts iscsid when it changed. Run once when the node joins.
func (c *Client) SetInitiator(ctx context.Context, a InitiatorArgs) error {
	if err := a.check(); err != nil {
		return err
	}
	name := san.InitiatorIQN(a.Cluster, a.Node)
	if c.initiatorName() == name {
		return nil
	}
	p := c.sys(filepath.Join(ISCSIDir, "initiatorname.iscsi"))
	content := "## Generated by HardyOS (hardyd-priv): this node's cluster initiator.\nInitiatorName=" + name + "\n"
	if err := rootfile.WriteAtomic(p, []byte(content), 0o644); err != nil {
		return err
	}
	if _, err := c.run(ctx, "systemctl", "restart", "iscsid.service"); err != nil {
		return fmt.Errorf("restarting iscsid with the new initiator name: %w", err)
	}
	c.log().Info("sanclient: initiator name set", "initiator", name)
	return nil
}

func (c *Client) initiatorName() string {
	b, err := os.ReadFile(c.sys(filepath.Join(ISCSIDir, "initiatorname.iscsi")))
	if err != nil {
		return ""
	}
	for _, l := range strings.Split(string(b), "\n") {
		if v, ok := strings.CutPrefix(strings.TrimSpace(l), "InitiatorName="); ok {
			return v
		}
	}
	return ""
}

// LoginArgs is sanclient.iscsi.login.
type LoginArgs struct {
	SessionArgs
	// Portals are the storage node's portals (two for multipath).
	Portals []netip.AddrPort `json:"portals"`
	// Interface is this node's storage network interface; every portal
	// must route through it.
	Interface string      `json:"interface"`
	CHAP      san.Secrets `json:"chap"`
}

// NodeRecord renders open-iscsi's node record for one portal of this
// node's target: manual startup (never logged in at boot: a fenced node
// must not reattach by itself), mutual CHAP, a short replacement timeout
// and NOP-Outs. Root writes it as a 0600 file, so the secrets never pass
// through iscsiadm's command line.
func NodeRecord(target string, portal netip.AddrPort, s san.Secrets) (string, error) {
	if err := s.Validate(); err != nil {
		return "", err
	}
	if !portal.Addr().Is4() || portal.Port() == 0 {
		return "", fmt.Errorf("portal %s isn't valid", portal)
	}
	lines := []string{
		"# BEGIN RECORD (HardyOS cluster storage; written by hardyd-priv)",
		"node.name = " + target,
		fmt.Sprintf("node.tpgt = %d", san.TPGTag),
		"node.startup = manual",
		"node.leading_login = No",
		"iface.iscsi_ifacename = default",
		"iface.transport_name = tcp",
		"node.discovery_type = static",
		"node.session.auth.authmethod = CHAP",
		"node.session.auth.username = " + s.User,
		"node.session.auth.password = " + s.Password,
		"node.session.auth.username_in = " + s.MutualUser,
		"node.session.auth.password_in = " + s.MutualPassword,
		fmt.Sprintf("node.session.timeo.replacement_timeout = %d", ReplacementTimeout),
		"node.session.err_timeo.abort_timeout = 15",
		"node.session.err_timeo.lu_reset_timeout = 30",
		"node.session.initial_login_retry_max = 4",
		"node.conn[0].address = " + portal.Addr().String(),
		fmt.Sprintf("node.conn[0].port = %d", portal.Port()),
		"node.conn[0].startup = manual",
		fmt.Sprintf("node.conn[0].timeo.noop_out_interval = %d", NOPInterval),
		fmt.Sprintf("node.conn[0].timeo.noop_out_timeout = %d", NOPInterval),
		"# END RECORD",
	}
	return strings.Join(lines, "\n") + "\n", nil
}

func (c *Client) recordDir(target string, portal netip.AddrPort) string {
	return c.sys(filepath.Join(ISCSIDir, "nodes", target, fmt.Sprintf("%s,%d,%d", portal.Addr(), portal.Port(), san.TPGTag)))
}

// Login writes the node records and logs in to every portal.
func (c *Client) Login(ctx context.Context, a LoginArgs) error {
	if err := a.check(); err != nil {
		return err
	}
	if len(a.Portals) == 0 || len(a.Portals) > 2 {
		return bad("one or two portals")
	}
	if err := a.CHAP.Validate(); err != nil {
		return &ValidationError{err}
	}
	for _, p := range a.Portals {
		if err := c.RouteCheck(ctx, a.Interface, p.Addr()); err != nil {
			return err
		}
	}
	target := san.TargetIQN(a.Cluster, a.Node)
	if c.initiatorName() != san.InitiatorIQN(a.Cluster, a.Node) {
		if err := c.SetInitiator(ctx, a.SessionArgs); err != nil {
			return err
		}
	}
	for _, p := range a.Portals {
		rec, err := NodeRecord(target, p, a.CHAP)
		if err != nil {
			return &ValidationError{err}
		}
		dir := c.recordDir(target, p)
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return err
		}
		_ = os.Chmod(filepath.Dir(dir), 0o700)
		if err := rootfile.WriteAtomic(filepath.Join(dir, "default"), []byte(rec), 0o600); err != nil {
			return err
		}
	}
	var errs []error
	for _, p := range a.Portals {
		res, err := c.Runner.Run(ctx, nil, "iscsiadm", "-m", "node", "-T", target, "-p", p.String(), "-I", "default", "--login")
		if err != nil {
			errs = append(errs, err)
			continue
		}
		if res.ExitCode != 0 && res.ExitCode != iscsiSessionExists {
			errs = append(errs, fmt.Errorf("logging in to %s: %w", p, &sysexec.CommandError{Name: "iscsiadm", Result: res}))
		}
	}
	if len(errs) == len(a.Portals) {
		return errors.Join(errs...)
	}
	if len(errs) > 0 {
		c.log().Warn("sanclient: one portal failed", "err", errors.Join(errs...))
	}
	return nil
}

// Logout logs out of this node's target on every portal. RemoveRecords
// also deletes the node records (leaving the cluster).
func (c *Client) Logout(ctx context.Context, a SessionArgs, removeRecords bool) error {
	if err := a.check(); err != nil {
		return err
	}
	target := san.TargetIQN(a.Cluster, a.Node)
	res, err := c.Runner.Run(ctx, nil, "iscsiadm", "-m", "node", "-T", target, "--logout")
	if err != nil {
		return err
	}
	if res.ExitCode != 0 && res.ExitCode != iscsiNoObjects {
		return &sysexec.CommandError{Name: "iscsiadm", Result: res}
	}
	if removeRecords {
		dir := c.sys(filepath.Join(ISCSIDir, "nodes", target))
		if err := os.RemoveAll(dir); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
	}
	return nil
}

// Rescan asks the target for its LUNs again (after a grant).
func (c *Client) Rescan(ctx context.Context, a SessionArgs) error {
	if err := a.check(); err != nil {
		return err
	}
	res, err := c.Runner.Run(ctx, nil, "iscsiadm", "-m", "node", "-T", san.TargetIQN(a.Cluster, a.Node), "--rescan")
	if err != nil {
		return err
	}
	if res.ExitCode != 0 {
		if res.ExitCode == iscsiNoObjects {
			return errNoSessions
		}
		return &sysexec.CommandError{Name: "iscsiadm", Result: res}
	}
	return nil
}

// Session is one iSCSI session.
type Session struct {
	ID     string `json:"id"`
	Portal string `json:"portal"`
	Target string `json:"target"`
}

var sessionRE = regexp.MustCompile(`^tcp: \[([0-9]+)\] ([^ ]+),[0-9]+ ([^ ]+)`)

func (c *Client) sessions(ctx context.Context) ([]Session, error) {
	res, err := c.Runner.Run(ctx, nil, "iscsiadm", "-m", "session")
	if err != nil {
		return nil, err
	}
	if res.ExitCode == iscsiNoObjects {
		return []Session{}, nil
	}
	if res.ExitCode != 0 {
		return []Session{}, &sysexec.CommandError{Name: "iscsiadm", Result: res}
	}
	out := []Session{}
	for _, l := range strings.Split(string(res.Stdout), "\n") {
		if m := sessionRE.FindStringSubmatch(strings.TrimSpace(l)); m != nil && strings.HasPrefix(m[3], cluster.IQNPrefix+".") {
			out = append(out, Session{ID: m[1], Portal: m[2], Target: m[3]})
		}
	}
	return out, nil
}
