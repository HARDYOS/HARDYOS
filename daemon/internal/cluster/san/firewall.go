package san

import (
	"errors"
	"fmt"
	"net/netip"
	"regexp"
	"slices"
	"strings"

	"github.com/hardyos/hardyos/daemon/internal/cluster"
)

// FirewallFile is the storage network's nft table (loaded with nft -f).
const FirewallFile = "/etc/hardyos/cluster-storage.nft"

// FirewallTable is its table.
const FirewallTable = "hardyos_cluster_storage"

// FirewallSpec is what san.firewall.apply renders.
type FirewallSpec struct {
	// Role: storage (iSCSI and NFS served) or compute (live migration
	// received).
	Role cluster.Role `json:"role"`
	// Interface is this server's storage network interface.
	Interface string `json:"interface"`
	// Subnet is the storage network; addresses from it arriving on any
	// other interface are dropped (spoofing).
	Subnet netip.Prefix `json:"subnet"`
	// Members are the active members' storage addresses: the only sources
	// allowed in.
	Members []netip.Addr `json:"members"`
	// Fenced nodes' addresses are dropped outright.
	Fenced []netip.Addr `json:"fenced"`
}

var ifRE = regexp.MustCompile(`^[a-zA-Z][a-zA-Z0-9_.-]{0,14}$`)

// Validate checks the spec (IPv4 storage networks; every address inside
// the subnet).
func (s FirewallSpec) Validate() error {
	var errs []error
	if s.Role != cluster.RoleStorage && s.Role != cluster.RoleCompute {
		errs = append(errs, fmt.Errorf("role %q isn't storage or compute", s.Role))
	}
	if !ifRE.MatchString(s.Interface) {
		errs = append(errs, fmt.Errorf("interface %q isn't valid", s.Interface))
	}
	if !s.Subnet.IsValid() || !s.Subnet.Addr().Is4() || s.Subnet.Bits() < 8 || s.Subnet.Bits() > 30 || s.Subnet.Masked() != s.Subnet {
		errs = append(errs, fmt.Errorf("storage subnet %s must be an IPv4 network from /8 to /30", s.Subnet))
	}
	for _, l := range [][]netip.Addr{s.Members, s.Fenced} {
		for _, a := range l {
			if !a.Is4() || !s.Subnet.Contains(a) {
				errs = append(errs, fmt.Errorf("%s isn't on the storage network %s", a, s.Subnet))
			}
		}
	}
	for _, a := range s.Fenced {
		if slices.Contains(s.Members, a) {
			errs = append(errs, fmt.Errorf("%s is both a member and fenced", a))
		}
	}
	return errors.Join(errs...)
}

func setLine(name string, l []netip.Addr) string {
	l = slices.Clone(l)
	slices.SortFunc(l, func(a, b netip.Addr) int { return a.Compare(b) })
	l = slices.Compact(l)
	var b strings.Builder
	fmt.Fprintf(&b, "\tset %s {\n\t\ttype ipv4_addr\n", name)
	if len(l) > 0 {
		s := make([]string, len(l))
		for i, a := range l {
			s[i] = a.String()
		}
		fmt.Fprintf(&b, "\t\telements = { %s }\n", strings.Join(s, ", "))
	}
	b.WriteString("\t}\n")
	return b.String()
}

// RenderFirewall renders the table. Loading it replaces the previous one
// atomically (one nft transaction).
func RenderFirewall(s FirewallSpec) (string, error) {
	if err := s.Validate(); err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by HardyOS (hardyd-priv): cluster storage network. Changes are overwritten.\n")
	fmt.Fprintf(&b, "table inet %s\ndelete table inet %s\ntable inet %s {\n", FirewallTable, FirewallTable, FirewallTable)
	b.WriteString(setLine("members", s.Members))
	b.WriteString(setLine("fenced", s.Fenced))
	b.WriteString("\tchain input {\n\t\ttype filter hook input priority filter - 5; policy accept;\n")
	sif := fmt.Sprintf("%q", s.Interface)
	fmt.Fprintf(&b, "\t\tiifname != %s ip saddr %s drop\n", sif, s.Subnet)
	fmt.Fprintf(&b, "\t\tiifname %s ip saddr @fenced drop\n", sif)
	switch s.Role {
	case cluster.RoleStorage:
		fmt.Fprintf(&b, "\t\ttcp dport %d iifname != %s drop\n", ISCSIPort, sif)
		fmt.Fprintf(&b, "\t\tiifname %s tcp dport { %d, %d } ip saddr @members accept\n", sif, NFSPort, ISCSIPort)
		fmt.Fprintf(&b, "\t\tiifname %s tcp dport { %d, %d } drop\n", sif, NFSPort, ISCSIPort)
	case cluster.RoleCompute:
		fmt.Fprintf(&b, "\t\tiifname %s tcp dport %d-%d ip saddr @members accept\n", sif, MigrateFirst, MigrateLast)
		fmt.Fprintf(&b, "\t\ttcp dport %d-%d drop\n", MigrateFirst, MigrateLast)
	}
	b.WriteString("\t}\n}\n")
	return b.String(), nil
}
