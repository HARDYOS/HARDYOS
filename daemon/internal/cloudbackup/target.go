// Package cloudbackup is the root side (hardyd-priv) of versioned cloud
// backups: restic repositories on S3-compatible storage (AWS, Wasabi,
// Cloudflare R2, MinIO) or Backblaze B2, backups taken from ZFS snapshots of
// shared folders, apps and VMs plus the server's settings, and restores
// that write through descriptors beneath the folder they restore into.
//
// hardyd never sees a cloud credential or a repository key after it was
// typed in: they are sealed in root's own state directory and only handed
// to restic through its environment and a pipe (never its command line).
// The one exception is the recovery kit, which hardyd asks for only after
// the administrator entered their password again. See docs/backup.md.
package cloudbackup

import (
	"errors"
	"fmt"
	"net"
	"net/url"
	"regexp"
	"strconv"
	"strings"
	"time"
	"unicode/utf8"
)

// Target kinds.
const (
	KindS3 = "s3"
	KindB2 = "b2"
	// KindLocal is a repository in a local folder. Tests only: refused
	// unless Root.AllowLocal is set.
	KindLocal = "local"
)

// Target is a place backups go: one restic repository. Nothing in it is
// secret; the credentials and the repository key are kept apart, sealed.
type Target struct {
	ID       string `json:"id"`
	Name     string `json:"name"`
	Kind     string `json:"kind"`
	Endpoint string `json:"endpoint,omitempty"` // s3: https://host[:port]
	Bucket   string `json:"bucket"`
	Prefix   string `json:"prefix,omitempty"` // folder inside the bucket
	Region   string `json:"region,omitempty"`
	// AllowLAN lets an S3 endpoint be on the local network (a MinIO on the
	// LAN). Loopback and link-local addresses are never allowed.
	AllowLAN bool `json:"allowLan,omitempty"`
	// Bandwidth limits in KiB/s (0 = none).
	LimitUploadKiB   int `json:"limitUploadKiB,omitempty"`
	LimitDownloadKiB int `json:"limitDownloadKiB,omitempty"`
	// Path is a KindLocal repository's folder (tests).
	Path      string    `json:"path,omitempty"`
	CreatedAt time.Time `json:"createdAt"`
	// AccessKeyHint is the access key's last four characters, so the
	// person can tell which key is in use (never the key itself).
	AccessKeyHint string `json:"accessKeyHint,omitempty"`
}

// Credentials open a target. They never leave hardyd-priv, except the
// repository password inside a recovery kit.
type Credentials struct {
	AccessKey string `json:"accessKey"`
	SecretKey string `json:"secretKey"`
	// RepoPassword is the restic repository's key: generated by HardyOS
	// when it creates the repository, typed in (from a recovery kit) when
	// connecting to an existing one.
	RepoPassword string `json:"repoPassword"`
}

var (
	idRE       = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,31}$`)
	s3BucketRE = regexp.MustCompile(`^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$`)
	b2BucketRE = regexp.MustCompile(`^[A-Za-z0-9-]{6,50}$`)
	prefixRE   = regexp.MustCompile(`^[A-Za-z0-9._-]+(/[A-Za-z0-9._-]+)*$`)
	regionRE   = regexp.MustCompile(`^[a-z0-9-]{0,32}$`)
	hostRE     = regexp.MustCompile(`^[A-Za-z0-9]([A-Za-z0-9-]{0,62})(\.[A-Za-z0-9]([A-Za-z0-9-]{0,62}))*$`)
	keyRE      = regexp.MustCompile(`^[\x21-\x7e]{1,256}$`)
)

// Problem is the caller's mistake, shown as is.
type Problem struct{ Msg string }

func (p *Problem) Error() string { return p.Msg }

func problemf(format string, a ...any) error { return &Problem{Msg: fmt.Sprintf(format, a...)} }

// ValidID checks a target's or task's id.
func ValidID(id string) error {
	if !idRE.MatchString(id) {
		return problemf("an id is 1-32 lower-case letters, digits or '-'")
	}
	return nil
}

// MaxKiB bounds a bandwidth limit (about 10 Gbit/s).
const MaxKiB = 1250000

// Normalize trims and validates a target. allowLocal permits KindLocal.
func (t *Target) Normalize(allowLocal bool) error {
	t.Name = strings.TrimSpace(t.Name)
	t.Endpoint = strings.TrimSuffix(strings.TrimSpace(t.Endpoint), "/")
	t.Bucket = strings.TrimSpace(t.Bucket)
	t.Prefix = strings.Trim(strings.TrimSpace(t.Prefix), "/")
	t.Region = strings.TrimSpace(t.Region)
	if err := ValidID(t.ID); err != nil {
		return err
	}
	if t.Name == "" || utf8.RuneCountInString(t.Name) > 64 || strings.ContainsFunc(t.Name, func(r rune) bool { return r < 0x20 || r == 0x7f }) {
		return problemf("give the destination a name of at most 64 characters")
	}
	if t.Prefix != "" && (len(t.Prefix) > 128 || !prefixRE.MatchString(t.Prefix) || strings.Contains("/"+t.Prefix+"/", "/../") || strings.Contains("/"+t.Prefix+"/", "/./")) {
		return problemf("the folder in the bucket may use letters, digits, '.', '_', '-' and '/' (at most 128)")
	}
	if !regionRE.MatchString(t.Region) {
		return problemf("the region looks wrong (like us-east-1)")
	}
	if t.LimitUploadKiB < 0 || t.LimitUploadKiB > MaxKiB || t.LimitDownloadKiB < 0 || t.LimitDownloadKiB > MaxKiB {
		return problemf("bandwidth limits are 0 (none) to %d KiB/s", MaxKiB)
	}
	switch t.Kind {
	case KindS3:
		if _, _, err := ParseEndpoint(t.Endpoint); err != nil {
			return err
		}
		if !s3BucketRE.MatchString(t.Bucket) || strings.Contains(t.Bucket, "..") {
			return problemf("an S3 bucket name is 3-63 lower-case letters, digits, '.' or '-'")
		}
		t.Path = ""
	case KindB2:
		t.Endpoint, t.Region, t.AllowLAN, t.Path = "", "", false, ""
		if !b2BucketRE.MatchString(t.Bucket) {
			return problemf("a B2 bucket name is 6-50 letters, digits or '-'")
		}
		if t.Prefix == "" {
			t.Prefix = "hardyos"
		}
	case KindLocal:
		if !allowLocal {
			return problemf("choose S3-compatible storage or Backblaze B2")
		}
		if !strings.HasPrefix(t.Path, "/") || strings.Contains(t.Path, "..") || strings.ContainsAny(t.Path, "\x00\n") {
			return problemf("a local repository needs an absolute path")
		}
		t.Endpoint, t.Bucket, t.Prefix = "", "", ""
	default:
		return problemf("choose S3-compatible storage or Backblaze B2")
	}
	return nil
}

// ParseEndpoint checks an S3 endpoint: https only, a host name or address
// and an optional port, nothing else (no path, user, query or fragment).
func ParseEndpoint(raw string) (host string, port int, err error) {
	bad := problemf("the endpoint must look like https://s3.example.com (https only, no path)")
	u, perr := url.Parse(raw)
	if perr != nil || u.Scheme != "https" || u.User != nil || u.RawQuery != "" || u.Fragment != "" || u.Opaque != "" || (u.Path != "" && u.Path != "/") {
		return "", 0, bad
	}
	host = u.Hostname()
	port = 443
	if p := u.Port(); p != "" {
		n, err := strconv.Atoi(p)
		if err != nil || n < 1 || n > 65535 {
			return "", 0, bad
		}
		port = n
	}
	if host == "" || len(host) > 253 {
		return "", 0, bad
	}
	if ip := net.ParseIP(host); ip == nil && !hostRE.MatchString(host) {
		return "", 0, bad
	}
	return strings.ToLower(host), port, nil
}

// Repository is the restic repository string for a target. It goes to
// restic in RESTIC_REPOSITORY, never on its command line.
func (t *Target) Repository() string {
	switch t.Kind {
	case KindS3:
		r := "s3:" + t.Endpoint + "/" + t.Bucket
		if t.Prefix != "" {
			r += "/" + t.Prefix
		}
		return r
	case KindB2:
		return "b2:" + t.Bucket + ":" + t.Prefix
	case KindLocal:
		return "local:" + t.Path
	}
	return ""
}

// CheckCredentials validates credentials for a target kind.
func CheckCredentials(kind string, c Credentials) error {
	if kind == KindLocal {
		return nil
	}
	if !keyRE.MatchString(c.AccessKey) || !keyRE.MatchString(c.SecretKey) {
		return problemf("enter the access key and secret key (printable characters, no spaces)")
	}
	return nil
}

// ValidRepoPassword checks a repository key typed in from a recovery kit.
func ValidRepoPassword(p string) error {
	if len(p) < 16 || len(p) > 512 || strings.ContainsAny(p, "\x00\n\r") {
		return problemf("the repository key from the recovery kit is 16-512 characters on one line")
	}
	return nil
}

// ErrNotFound means there's no target or task with that id.
var ErrNotFound = errors.New("there's no backup destination with that id")

func hint(key string) string {
	if len(key) <= 4 {
		return ""
	}
	return "…" + key[len(key)-4:]
}
