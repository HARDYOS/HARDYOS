package nbstandby

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/hardyos/hardyos/daemon/internal/ports"
	"github.com/hardyos/hardyos/daemon/internal/sysexec"
)

// Networking (decision 426). The netbird-standby app's ports are dropped
// from anything but loopback unless HardyOS has taken over (a prerouting
// filter, before Docker's DNAT, so a published port can't slip past it).
// While taken over they are open, and HardyOS itself reaches the local
// standby instead of the internet: /etc/hosts maps the NetBird hostname to
// LocalAddr, which an output DNAT sends to the standby's ports. So the
// NetBird client, hardyd's NetBird API calls and peer checks never depend on
// the VPS or on the router sending the server's own traffic back in.

// LocalAddr is the loopback address the hostname points to while taken over.
const LocalAddr = "127.0.77.1"

// NFTTable is hardyd-priv's own table for the standby.
const NFTTable = "hardyos_nbstandby"

const (
	hostsBegin = "# BEGIN hardyos netbird standby (managed by HardyOS; removed on hand-back)"
	hostsEnd   = "# END hardyos netbird standby"
)

// NFTRules is the table for open (taken over) or closed.
func NFTRules(open bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by HardyOS (NetBird standby, decision 426). Do not edit.\n")
	fmt.Fprintf(&b, "table inet %s\ndelete table inet %s\ntable inet %s {\n", NFTTable, NFTTable, NFTTable)
	if !open {
		fmt.Fprintf(&b, "  chain prerouting {\n    type filter hook prerouting priority -150; policy accept;\n")
		fmt.Fprintf(&b, "    iifname \"lo\" accept\n")
		fmt.Fprintf(&b, "    tcp dport { %d, %d } drop\n", ports.NetBirdStandbyHTTP, ports.NetBirdStandbyHTTPS)
		fmt.Fprintf(&b, "    udp dport %d drop\n  }\n", ports.NetBirdStandbySTUN)
		// The containers themselves, on their bridge (from the host, other
		// containers or anything routed), except each other.
		fmt.Fprintf(&b, "  chain forward {\n    type filter hook forward priority -150; policy accept;\n")
		fmt.Fprintf(&b, "    ip saddr != %s ip daddr %s drop\n  }\n", ports.NetBirdStandbySubnet, ports.NetBirdStandbySubnet)
		fmt.Fprintf(&b, "  chain output {\n    type filter hook output priority -150; policy accept;\n")
		fmt.Fprintf(&b, "    ip daddr %s drop\n  }\n", ports.NetBirdStandbySubnet)
	} else {
		fmt.Fprintf(&b, "  chain output {\n    type nat hook output priority -110; policy accept;\n")
		fmt.Fprintf(&b, "    ip daddr %s tcp dport %d dnat ip to 127.0.0.1:%d\n", LocalAddr, ports.HTTP, ports.NetBirdStandbyHTTP)
		fmt.Fprintf(&b, "    ip daddr %s tcp dport %d dnat ip to 127.0.0.1:%d\n", LocalAddr, ports.HTTPS, ports.NetBirdStandbyHTTPS)
		fmt.Fprintf(&b, "    ip daddr %s udp dport %d dnat ip to 127.0.0.1:%d\n  }\n", LocalAddr, ports.NetBirdSTUN, ports.NetBirdStandbySTUN)
	}
	b.WriteString("}\n")
	return b.String()
}

// NFTRemove deletes the table (the app was removed or the standby forgotten).
func NFTRemove() string {
	return fmt.Sprintf("table inet %s\ndelete table inet %s\n", NFTTable, NFTTable)
}

// UpdateHosts returns /etc/hosts with HardyOS's block for host (or without
// it when host is ""), leaving every other line as it was.
func UpdateHosts(old []byte, host string) ([]byte, error) {
	if host != "" && !ValidHostname(host) {
		return nil, errors.New("bad hostname")
	}
	var out []string
	in := false
	for _, l := range strings.Split(strings.TrimRight(string(old), "\n"), "\n") {
		switch {
		case l == hostsBegin:
			in = true
			continue
		case l == hostsEnd:
			in = false
			continue
		case in:
			continue
		}
		out = append(out, l)
	}
	if len(out) == 1 && out[0] == "" {
		out = nil
	}
	if host != "" {
		out = append(out, hostsBegin, LocalAddr+"\t"+host, hostsEnd)
	}
	return []byte(strings.Join(out, "\n") + "\n"), nil
}

// System applies the rules and the hosts entry on the real system.
type System struct {
	Runner sysexec.Runner
	// Root prefixes /etc/hosts (tests); "/" in production.
	Root string
}

// Apply sets the table (closed, or open with host's entry when open).
func (s *System) Apply(ctx context.Context, open bool, host string) error {
	if open && !ValidHostname(host) {
		return errors.New("bad hostname")
	}
	if open {
		if err := s.UserlandProxy(); err != nil {
			return err
		}
	}
	if err := s.nft(ctx, NFTRules(open)); err != nil {
		return err
	}
	if !open {
		host = ""
	}
	return s.hosts(host)
}

// Remove takes the table and the hosts entry away.
func (s *System) Remove(ctx context.Context) error {
	if err := s.nft(ctx, NFTRemove()); err != nil {
		return err
	}
	return s.hosts("")
}

// UserlandProxy checks Docker's userland proxy is on (Docker's default):
// this server reaches the standby at 127.0.0.1:<published port>, which only
// the userland proxy answers (decision 426).
func (s *System) UserlandProxy() error {
	b, err := os.ReadFile(filepath.Join(s.root(), "etc", "docker", "daemon.json"))
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	var cfg map[string]any
	if json.Unmarshal(b, &cfg) != nil {
		return nil
	}
	if v, ok := cfg["userland-proxy"].(bool); ok && !v {
		return errors.New("Docker's userland proxy is off (/etc/docker/daemon.json): this server couldn't reach its own standby during a take-over")
	}
	return nil
}

func (s *System) root() string {
	if s.Root == "" {
		return "/"
	}
	return s.Root
}

func (s *System) nft(ctx context.Context, rules string) error {
	res, err := s.Runner.Run(ctx, []byte(rules), "nft", "-f", "-")
	if err != nil {
		return err
	}
	if res.ExitCode != 0 {
		return &sysexec.CommandError{Name: "nft", Result: res}
	}
	return nil
}

func (s *System) hosts(host string) error {
	root := s.Root
	if root == "" {
		root = "/"
	}
	p := filepath.Join(root, "etc", "hosts")
	old, err := os.ReadFile(p)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	nb, err := UpdateHosts(old, host)
	if err != nil {
		return err
	}
	if bytes.Equal(nb, old) {
		return nil
	}
	// /etc is root's: a temporary file next to it, synced, then renamed.
	tmp, err := os.CreateTemp(filepath.Dir(p), ".hosts.hardyos-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(nb); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), p)
}
